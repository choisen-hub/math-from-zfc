def show_patterns():
    """구성 과정에서 반복된 패턴을 분석합니다."""
    print("\n\n반복된 패턴 분석")
    print("=" * 60)

    print("""
  1. "확장" 패턴: ℕ → ℤ → ℚ → ℝ
  ────────────────────────────────
  각 단계에서:
    이전 체계의 한계 → 쌍(또는 부분집합)의 동치류 → 새 체계

    ℕ → ℤ:  뺄셈 불가 → 자연수 쌍 (a,b)의 동치류
    ℤ → ℚ:  나눗셈 불가 → 정수 쌍 (a,b)의 동치류
    ℚ → ℝ:  구멍 존재 → 유리수의 부분집합 (데데킨트 절단)

  2. "매장" 패턴
  ────────────────
  각 단계에서 이전 체계가 새 체계 안에 보존적으로 포함됨:
    ℕ ⊂ ℤ ⊂ ℚ ⊂ ℝ
    n ↦ (n,0)  z ↦ z/1  q ↦ 절단

  매장은 연산을 보존:
    f(a + b) = f(a) + f(b)
    f(a × b) = f(a) × f(b)

  3. "추상화" 패턴 (Phase 7)
  ──────────────────────────
  구체적 예시에서 공통 구조를 추출:
    (ℤ, +), (ℚ\\{0}, ×), (S₃, ∘)  →  "군" (Group)
    (ℤ, +, ×)                       →  "환" (Ring)
    (ℚ, +, ×), (ℝ, +, ×)           →  "체" (Field)
""")


