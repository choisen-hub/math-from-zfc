#  공리 7: 치환 공리꼴 (Axiom Schema of Replacement)
# ============================================================================

class AxiomSchemaOfReplacement:
    """
    치환 공리꼴: 집합의 각 원소를 함수로 변환한 결과도 집합이다.

    형식적 진술:
        임의의 함수적 성질 φ(x, y)에 대해:
        ∀A [ (∀x ∈ A, ∃!y, φ(x,y)) → ∃B ∀y(y ∈ B ⟺ ∃x ∈ A, φ(x,y)) ]

    쉽게 말하면:
        A가 집합이고 F가 함수이면, F[A] = {F(x) : x ∈ A}도 집합이다.

    왜 필요한가?
    -----------
    Phase 3에서 덧셈과 곱셈을 재귀적으로 정의할 때,
    "재귀적 정의가 실제로 함수를 만들어낸다"는 것을 보장하는 데 사용됩니다.

    이 공리가 없으면?
    ----------------
    재귀적 정의의 정당성을 보장할 수 없습니다.
    "n + S(m) = S(n + m)"이라는 정의가 실제로 잘 정의된 함수를 만드는지
    확인할 수 없게 됩니다.

    예시:
        1. A = {1, 2, 3}, F(x) = x² → F[A] = {1, 4, 9}
        2. A = {0, 1, 2, 3}, F(x) = 2x → F[A] = {0, 2, 4, 6}
        3. A = ℕ, F(n) = n번째 피보나치 수 → F[ℕ]은 집합이다
    """

    @staticmethod
    def demonstrate():
        """치환 공리꼴을 시뮬레이션합니다."""
        print("=" * 60)
        print("공리 7: 치환 공리꼴 (Axiom Schema of Replacement)")
        print("  \"집합의 각 원소를 함수로 변환한 결과도 집합이다\"")
        print("=" * 60)

        A = {1, 2, 3, 4, 5}
        F_square = {x: x**2 for x in A}
        F_double = {x: 2*x for x in A}

        print(f"\n  A = {sorted(A)}")
        print(f"  F(x) = x² → F[A] = {sorted(F_square.values())}")
        print(f"  G(x) = 2x → G[A] = {sorted(F_double.values())}")

        print(f"\n  💡 핵심 통찰:")
        print(f"  분류 공리꼴: A에서 '걸러내기' → A의 부분집합")
        print(f"  치환 공리꼴: A를 '변환하기' → 전혀 다른 집합도 가능")
        print(f"  치환 공리꼴이 분류 공리꼴보다 더 강력합니다.")
        print()


