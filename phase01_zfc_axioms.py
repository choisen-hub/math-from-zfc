#  공리 9: 선택 공리 (Axiom of Choice)
# ============================================================================

class AxiomOfChoice:
    """
    선택 공리: 비어있지 않은 집합들의 모임에서, 각 집합에서 하나씩 고를 수 있다.

    형식적 진술:
        ∀F [ (∀A ∈ F, A ≠ ∅) → ∃f: F → ∪F, ∀A ∈ F, f(A) ∈ A ]
    즉, "선택 함수"(choice function)가 존재한다.

    왜 필요한가?
    -----------
    유한 개의 집합에서 원소를 고르는 것은 다른 공리들로 충분합니다.
    하지만 무한히 많은 집합 각각에서 동시에 하나씩 고르는 것은
    별도의 공리가 필요합니다.

    직관적으로는 너무 당연해 보입니다:
    "각 집합이 비어있지 않으니, 하나씩 고를 수 있지 않은가?"
    하지만 "무한히 많은 선택을 동시에 한다"는 것은
    구체적인 선택 규칙을 제시할 수 없는 경우가 있습니다.

    선택 공리의 놀라운 결과: 바나흐-타르스키 역설
    ------------------------------------------
    선택 공리를 인정하면, 하나의 구를 유한 개의 조각으로 분해한 후
    재조립하여 원래와 같은 크기의 구 두 개를 만들 수 있습니다!
    (물론 이 "조각"은 일상적 의미의 조각이 아니라,
     측도를 부여할 수 없는 괴상한 집합입니다.)

    이 공리가 없으면?
    ----------------
    - 모든 벡터공간이 기저를 가진다는 것을 증명할 수 없음
    - 임의의 환의 극대 이상의 존재를 보장할 수 없음
    - 초른의 보조정리, 조른의 정리 등이 성립하지 않음

    예시:
        1. 유한한 경우: {{1,2}, {3,4}, {5,6}} → f: {1,2}↦1, {3,4}↦3, {5,6}↦5
           (선택 공리 없이도 가능)
        2. 가산 무한한 경우: {A₁, A₂, A₃, ...} 각각에서 하나씩
           (선택 규칙이 명시적이면 공리 없이도 가능)
        3. 비가산 무한한 경우: 선택 공리가 진정으로 필요한 경우
    """

    @staticmethod
    def demonstrate():
        """선택 공리의 의미를 시뮬레이션합니다."""
        print("=" * 60)
        print("공리 9: 선택 공리 (Axiom of Choice)")
        print("  \"비어있지 않은 집합들에서 각각 하나씩 고를 수 있다\"")
        print("=" * 60)

        # 유한한 경우 시뮬레이션
        family = [{'사과', '배'}, {'고양이', '개'}, {'빨강', '파랑', '초록'}]
        # 간단한 선택 함수: 각 집합에서 "첫 번째" 원소를 고름
        choices = [min(s) for s in family]
        print(f"\n  유한한 경우 (선택 공리 불필요):")
        for i, (s, c) in enumerate(zip(family, choices)):
            print(f"    A{i+1} = {s} → 선택: '{c}'")

        print(f"\n  💡 선택 공리가 진정으로 필요한 경우:")
        print(f"  무한히 많은 집합 각각에서 동시에 원소를 고를 때,")
        print(f"  구체적인 선택 규칙을 제시할 수 없는 경우가 있습니다.")

        print(f"\n  ⚡ 바나흐-타르스키 역설:")
        print(f"  선택 공리를 인정하면, 하나의 구를 유한 개 조각으로 분해 후")
        print(f"  재조립하여 같은 크기의 구 2개를 만들 수 있습니다!")
        print(f"  → 이것이 선택 공리를 둘러싼 논란의 핵심입니다.")

        print(f"\n  📝 이 프로그램에서의 역할:")
        print(f"  Phase 2-8에서는 선택 공리를 명시적으로 사용하지 않습니다.")
        print(f"  선택 공리는 주로 고급 수학(함수해석학, 대수학 등)에서 필요합니다.")
        print()


