#  공리 8: 무한 공리 (Axiom of Infinity)
# ============================================================================

class AxiomOfInfinity:
    """
    무한 공리: 자연수 전체를 포함하는 무한 집합이 존재한다.

    형식적 진술:
        ∃I [ ∅ ∈ I ∧ ∀x(x ∈ I → x ∪ {x} ∈ I) ]
    즉, ∅을 포함하고, 후계자 연산에 대해 닫혀 있는 집합이 존재한다.

    왜 필요한가?
    -----------
    다른 공리들(공집합, 짝, 합집합)로는 임의의 유한 집합을 만들 수 있지만,
    그것들을 "전부 모은" 무한 집합이 존재한다는 보장은 없습니다.

    0을 만들 수 있고, 0으로부터 1을, 1로부터 2를 만들 수 있지만,
    {0, 1, 2, 3, ...} 전체가 하나의 집합인지는 다른 문제입니다.

    무한 공리는 이 "점프"를 가능하게 합니다:
    유한한 구성 단계를 넘어서, 무한한 전체를 한꺼번에 잡습니다.

    이 공리가 없으면?
    ----------------
    유한 집합만 존재하는 세계가 가능합니다.
    자연수를 하나하나 만들 수는 있지만, "자연수 전체의 집합 ℕ"이
    존재한다고 말할 수 없습니다.
    수학적 귀납법의 정당화가 불가능해집니다.

    예시:
        1. ∅ ∈ I (시작: 0이 있다)
        2. ∅ ∈ I → {∅} ∈ I (0이 있으면 1도 있다)
        3. {∅} ∈ I → {∅, {∅}} ∈ I (1이 있으면 2도 있다)
        → 이 모든 것을 담은 I가 존재한다!
    """

    @staticmethod
    def demonstrate():
        """무한 공리의 의미를 시뮬레이션합니다."""
        print("=" * 60)
        print("공리 8: 무한 공리 (Axiom of Infinity)")
        print("  \"자연수 전체를 포함하는 무한 집합이 존재한다\"")
        print("=" * 60)

        # 유한한 시뮬레이션
        print(f"\n  다른 공리들로 만들 수 있는 것:")
        print(f"  0 = ∅")
        print(f"  1 = {{∅}} = S(0)")
        print(f"  2 = {{∅, {{∅}}}} = S(1)")
        print(f"  3 = {{∅, {{∅}}, {{∅, {{∅}}}}}} = S(2)")
        print(f"  ... 각각의 n은 만들 수 있지만 ...")

        print(f"\n  무한 공리가 추가로 보장하는 것:")
        print(f"  ℕ = {{0, 1, 2, 3, ...}} — 이 전체가 하나의 집합!")
        print(f"\n  ⚠ 이것은 자명하지 않습니다!")
        print(f"  '각각의 n을 만들 수 있다' ≠ '전부를 모은 것이 존재한다'")
        print(f"  유한 → 무한의 점프에는 별도의 공리가 필요합니다.")

        # 귀납법과의 연결
        print(f"\n  무한 공리 → 수학적 귀납법:")
        print(f"  ℕ가 집합으로 존재하므로, ℕ 위에서 귀납법을 적용할 수 있습니다.")
        print(f"  (Phase 2에서 자세히 다룹니다)")
        print()


