#  (선택적) 정칙성 공리 (Axiom of Foundation / Regularity)
# ============================================================================

class AxiomOfFoundation:
    """
    정칙성 공리: 비어있지 않은 모든 집합 A에 대해,
    A와 서로소인(교집합이 공집합인) 원소가 A 안에 존재한다.

    형식적 진술:
        ∀A [ A ≠ ∅ → ∃x ∈ A, x ∩ A = ∅ ]

    왜 필요한가?
    -----------
    이 공리는 집합의 "순환적 포함"을 금지합니다.
    - x ∈ x 불가능 (자기 자신을 원소로 포함할 수 없음)
    - x ∈ y ∈ x 불가능 (순환적 포함 금지)
    - 무한 하강 사슬 ... ∈ x₃ ∈ x₂ ∈ x₁ 불가능

    이것은 집합의 세계에 "깊이"(depth) 구조를 부여합니다:
    모든 집합은 공집합에서 시작하여 유한 단계로 구성됩니다.

    이 공리가 없으면?
    ----------------
    x = {x}인 "괴상한 집합"이 존재할 수 있습니다.
    집합의 세계가 well-founded하지 않게 됩니다.
    (실제로 정칙성 공리 없는 집합론도 연구됩니다: 비정칙 집합론)

    예시:
        1. A = {{∅}} → ∅이 아닌 원소 {∅}가 있고, {∅} ∩ {{∅}} = ∅
        2. A = {1, {1, 2}} → 1 ∈ A이고 1 ∩ A = ∅ (1은 자연수, 즉 집합으로서 {∅})
        3. x ∈ x는 불가능 — {x} ∩ {x} = {x} ≠ ∅이므로 정칙성에 위배
    """

    @staticmethod
    def demonstrate():
        """정칙성 공리의 의미를 설명합니다."""
        print("=" * 60)
        print("(선택적) 정칙성 공리 (Axiom of Foundation)")
        print("  \"집합은 자기 자신을 원소로 포함할 수 없다\"")
        print("=" * 60)

        print(f"\n  정칙성 공리가 금지하는 것:")
        print(f"  ✗ x ∈ x          (자기포함)")
        print(f"  ✗ x ∈ y ∈ x      (순환포함)")
        print(f"  ✗ ... ∈ x₃ ∈ x₂ ∈ x₁  (무한하강)")

        print(f"\n  정칙성 공리가 보장하는 것:")
        print(f"  모든 집합은 '깊이'(rank)를 가진다:")
        print(f"  V₀ = ∅")
        print(f"  V₁ = P(V₀) = {{∅}}")
        print(f"  V₂ = P(V₁) = {{∅, {{∅}}}}")
        print(f"  V₃ = P(V₂) = ...")
        print(f"  모든 집합은 어떤 V_α에 처음 등장합니다.")
        print(f"\n  → 집합의 세계는 '바닥(∅)에서 쌓아올린' 구조입니다.")
        print()


