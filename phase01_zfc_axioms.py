"""
Phase 1: ZFC 공리계 — 집합의 세계를 여는 규칙들
=================================================

수학의 모든 것을 세우려면 출발점이 필요합니다.

우리가 일상에서 "수", "함수", "공간"이라고 부르는 것들은
어디에서 오는 걸까요? "1 + 1 = 2"가 참인 이유는 무엇일까요?

이 질문에 답하려면, 수학의 가장 깊은 바닥까지 내려가야 합니다.
그 바닥에 있는 것이 바로 ZFC 공리계입니다.

ZFC는 Zermelo-Fraenkel with Choice의 약자로,
현대 수학의 표준적인 토대(foundation)입니다.

ZFC의 출발점은 놀라울 만큼 간소합니다:
  - 원초적 개념 1: "집합" (set) — 정의하지 않는 기본 개념
  - 원초적 개념 2: "원소 관계" (∈) — "x는 A의 원소이다" (x ∈ A)
  - 그리고 9개의 공리 — 집합을 만들고 조작하는 규칙

이 두 개의 개념과 9개의 규칙으로부터 자연수, 정수, 유리수, 실수,
함수, 공간, 그리고 현대 수학의 거의 모든 것이 구성됩니다.

역사적 맥락
-----------
19세기 말, 게오르크 칸토어(Georg Cantor)는 집합론을 창시했습니다.
칸토어의 "소박한 집합론"(naive set theory)은 강력했지만,
"임의의 성질 P에 대해 {x : P(x)}는 집합이다"라는 무제한적인
집합 구성 원리를 허용했습니다.

1901년, 버트런드 러셀(Bertrand Russell)은 이 원리가 모순을 낳음을 발견했습니다:
  R = {x : x ∉ x} (자기 자신을 원소로 포함하지 않는 모든 집합의 모임)
  → R ∈ R이면 R ∉ R이고, R ∉ R이면 R ∈ R. 모순!

이것이 유명한 "러셀의 역설"(Russell's paradox)입니다.

에른스트 체르멜로(Ernst Zermelo)는 1908년에 집합 구성에 제한을 두는
공리적 체계를 제안하여 이 역설을 피했습니다.
이후 아브라함 프렝켈(Abraham Fraenkel)이 보강하여
오늘날의 ZFC가 완성되었습니다.

중요한 주의
-----------
이 모듈에서 Python의 내장 set을 교육적 도구로 활용하지만,
Python의 set ≠ ZFC의 집합입니다!

차이점:
  - Python set은 유한하지만, ZFC 집합은 무한할 수 있습니다.
  - Python set의 원소는 해시 가능한 값이지만, ZFC에서는 집합의 원소도 집합입니다.
  - Python set은 컴퓨터의 메모리 안에 있지만, ZFC 집합은 수학적 대상입니다.

Python 코드는 ZFC의 아이디어를 "체험"하기 위한 유한한 시뮬레이션일 뿐입니다.
"""


# ============================================================================
#  공리 1: 외연 공리 (Axiom of Extensionality)
# ============================================================================

class AxiomOfExtensionality:
    """
    외연 공리: 두 집합이 같은 원소를 가지면, 두 집합은 같다.

    형식적 진술:
        ∀A ∀B [ (∀x, x ∈ A ⟺ x ∈ B) → A = B ]

    왜 필요한가?
    -----------
    이 공리는 집합의 "정체성"(identity)을 정합니다.
    집합은 오직 그 원소에 의해서만 결정됩니다.
    집합이 어떻게 정의되었는지, 어떤 순서로 나열되었는지는 중요하지 않습니다.

    이 공리가 없으면?
    ----------------
    {1, 2, 3}과 {3, 1, 2}가 같은 집합인지 판단할 근거가 없습니다.
    "이름은 다르지만 내용이 같은 두 집합"을 동일시할 수 없게 됩니다.

    예시:
        1. {1, 2, 3} = {3, 1, 2} = {1, 2, 3, 2, 1}
           (원소가 같으므로 같은 집합)
        2. {a, b} = {b, a}
           (순서는 무관)
        3. {x : x는 짝수이고 소수} = {2}
           (정의 방식이 달라도 원소가 같으면 같은 집합)
    """

    @staticmethod
    def demonstrate():
        """외연 공리를 Python set으로 시뮬레이션합니다."""
        print("=" * 60)
        print("공리 1: 외연 공리 (Axiom of Extensionality)")
        print("  \"두 집합이 같은 원소를 가지면 같다\"")
        print("=" * 60)

        # 예시 1: 순서가 달라도 같은 집합
        A = {1, 2, 3}
        B = {3, 1, 2}
        print(f"\n  예시 1: A = {{1, 2, 3}}, B = {{3, 1, 2}}")
        print(f"  A == B? {A == B}  ← 원소가 같으므로 같은 집합!")

        # 예시 2: 중복은 무시됨
        C = {1, 2, 3, 2, 1}
        print(f"\n  예시 2: C = {{1, 2, 3, 2, 1}}")
        print(f"  A == C? {A == C}  ← 중복을 제거하면 같은 원소")

        # 예시 3: 정의 방식이 달라도
        D = {x for x in range(1, 100) if x % 2 == 0 and all(x % d != 0 for d in range(2, x)) and x > 1}
        # 2만 짝수이면서 소수
        D = {2}
        E = {x for x in range(10) if x == 2}
        print(f"\n  예시 3: D = {{짝수인 소수}} = {D}")
        print(f"          E = {{10 미만의 수 중 2인 것}} = {E}")
        print(f"  D == E? {D == E}  ← 정의 방식이 달라도 원소가 같으면 같다!")

        # 반사실적: 외연 공리가 없다면?
        print(f"\n  ⚠ 반사실적 시나리오:")
        print(f"  외연 공리가 없으면, '짝수인 소수의 모임'과 '{{2}}'가")
        print(f"  같은 집합인지 판단할 원칙적 근거가 없습니다.")
        print()


# ============================================================================
#  공리 2: 공집합 공리 (Axiom of Empty Set)
# ============================================================================

class AxiomOfEmptySet:
    """
    공집합 공리: 원소가 하나도 없는 집합이 존재한다.

    형식적 진술:
        ∃∅ ∀x, x ∉ ∅

    왜 필요한가?
    -----------
    "아무것도 없음"이 존재해야 합니다!
    이것은 철학적으로도 깊은 의미를 가집니다.

    공집합 ∅은 모든 것의 시작점입니다.
    Phase 2에서 보게 되겠지만, 우리는 이 "아무것도 없음"으로부터
    모든 자연수를 구성할 것입니다:
        0 = ∅
        1 = {∅}
        2 = {∅, {∅}}
        ...

    이 공리가 없으면?
    ----------------
    출발점이 없습니다! 자연수를 구성할 씨앗이 없습니다.
    집합 이론의 어떤 구성도 시작할 수 없게 됩니다.

    예시:
        1. ∅ = {} — 원소가 하나도 없는 집합
        2. ∅ ≠ {∅} — 공집합과, 공집합을 원소로 가진 집합은 다릅니다!
           ({∅}는 원소가 1개 있으므로 비어있지 않습니다)
        3. |∅| = 0 — 공집합의 크기는 0
    """

    @staticmethod
    def demonstrate():
        """공집합 공리를 시뮬레이션합니다."""
        print("=" * 60)
        print("공리 2: 공집합 공리 (Axiom of Empty Set)")
        print("  \"원소가 하나도 없는 집합이 존재한다\"")
        print("=" * 60)

        empty = set()
        print(f"\n  공집합: ∅ = {empty}")
        print(f"  원소의 수: |∅| = {len(empty)}")

        # ∅ ≠ {∅} 구별
        print(f"\n  중요한 구별:")
        print(f"  ∅  = {{}}       (원소 0개 — 아무것도 없음)")
        print(f"  {{∅}} = {{{{}}}}    (원소 1개 — '아무것도 없음'을 담은 집합)")
        print(f"  ∅ ≠ {{∅}}!     (원소 개수가 다르므로 외연 공리에 의해 다른 집합)")

        # 왜 "아무것도 없음"이 존재해야 하는가?
        print(f"\n  💡 왜 '아무것도 없음'이 존재해야 하는가?")
        print(f"  → 0이라는 수를 만들려면 0에 대응하는 집합이 필요합니다.")
        print(f"  → ∅이 바로 그 집합입니다. (Phase 2에서 다시 만납니다)")
        print(f"  → '무(無)에서 유(有)를 만든다'의 첫 걸음입니다.")
        print()


# ============================================================================
#  공리 3: 짝 공리 (Axiom of Pairing)
# ============================================================================

class AxiomOfPairing:
    """
    짝 공리: 임의의 두 집합 a, b에 대해 {a, b}가 존재한다.

    형식적 진술:
        ∀a ∀b ∃C ∀x [ x ∈ C ⟺ (x = a ∨ x = b) ]

    왜 필요한가?
    -----------
    두 대상을 "하나로 묶는" 능력을 보장합니다.
    이것이 없으면 순서쌍을 만들 수 없고,
    순서쌍이 없으면 함수를 정의할 수 없고,
    함수가 없으면 수학의 대부분이 무너집니다.

    특히 순서쌍 (a, b)의 쿠라토프스키(Kuratowski) 정의:
        (a, b) = {{a}, {a, b}}
    는 짝 공리를 두 번 사용합니다:
        1. {a}를 만들고 (a = b인 경우의 짝 공리)
        2. {a, b}를 만들고
        3. 이 둘을 다시 짝으로 묶어 {{a}, {a, b}}를 만듭니다

    이 공리가 없으면?
    ----------------
    공집합 외에 다른 집합을 만들 수 없습니다.
    {∅}조차 만들 수 없으므로, 후계자 함수가 정의되지 않고,
    자연수 1, 2, 3, ...을 만들 수 없습니다.

    예시:
        1. ∅과 ∅으로 짝을 만들면: {∅, ∅} = {∅} (외연 공리에 의해)
        2. ∅과 {∅}으로 짝을 만들면: {∅, {∅}} (이것이 자연수 2!)
        3. 순서쌍 (a, b) = {{a}, {a, b}}
    """

    @staticmethod
    def demonstrate():
        """짝 공리와 순서쌍의 구성을 시뮬레이션합니다."""
        print("=" * 60)
        print("공리 3: 짝 공리 (Axiom of Pairing)")
        print("  \"임의의 두 집합으로 짝을 만들 수 있다\"")
        print("=" * 60)

        # 짝 만들기
        print(f"\n  짝 공리로 만들 수 있는 것:")
        print(f"  {{a, b}}를 만들 수 있다 (a, b는 임의의 집합)")
        print(f"  특히 a = b이면 {{a, a}} = {{a}} (단원소 집합)")

        # 순서쌍의 쿠라토프스키 정의
        print(f"\n  순서쌍의 쿠라토프스키(Kuratowski) 정의:")
        print(f"  (a, b) = {{{{a}}, {{a, b}}}}")
        print(f"\n  왜 이렇게 정의하는가?")
        print(f"  → 순서쌍의 핵심: (a, b) = (c, d) ⟺ a=c이고 b=d")
        print(f"  → 일반 집합 {{a, b}}는 순서가 없다: {{a, b}} = {{b, a}}")
        print(f"  → 쿠라토프스키 정의는 순서를 인코딩한다:")
        print(f"     {{{{a}}, {{a, b}}}}에서 '두 원소에 공통인 것'이 첫 번째(a)")
        print(f"     '하나에만 있는 것'이 두 번째(b)")

        # 구체적 예시
        def kuratowski_pair(a, b):
            """순서쌍 (a,b)의 쿠라토프스키 표현"""
            return frozenset({frozenset({a}), frozenset({a, b})})

        p1 = kuratowski_pair(1, 2)
        p2 = kuratowski_pair(2, 1)
        print(f"\n  예시:")
        print(f"  (1, 2) = {{{{1}}, {{1, 2}}}}")
        print(f"  (2, 1) = {{{{2}}, {{2, 1}}}} = {{{{2}}, {{1, 2}}}}")
        print(f"  (1,2) == (2,1)? {p1 == p2}  ← 순서가 보존된다!")
        print()


# ============================================================================
#  공리 4: 합집합 공리 (Axiom of Union)
# ============================================================================

class AxiomOfUnion:
    """
    합집합 공리: 집합들의 집합이 주어지면, 모든 원소를 합칠 수 있다.

    형식적 진술:
        ∀F ∃U ∀x [ x ∈ U ⟺ ∃A(A ∈ F ∧ x ∈ A) ]
    즉, ∪F = {x : ∃A ∈ F, x ∈ A}

    왜 필요한가?
    -----------
    여러 집합의 원소를 하나로 모으는 능력을 보장합니다.
    특히 후계자 함수 S(n) = n ∪ {n}에서 합집합 연산이 필수적입니다.

    이 공리가 없으면?
    ----------------
    n ∪ {n}을 만들 수 없으므로, 1 다음에 2를 만들 수 없고,
    자연수의 연쇄를 구성할 수 없습니다.

    예시:
        1. ∪{{1,2}, {2,3}, {3,4}} = {1, 2, 3, 4}
        2. ∪{∅, {∅}} = {∅} = 1 (폰 노이만 구성에서)
        3. S(2) = 2 ∪ {2} = {0,1} ∪ {2} = {0,1,2} = 3
    """

    @staticmethod
    def demonstrate():
        """합집합 공리를 시뮬레이션합니다."""
        print("=" * 60)
        print("공리 4: 합집합 공리 (Axiom of Union)")
        print("  \"집합들의 집합에서 모든 원소를 합칠 수 있다\"")
        print("=" * 60)

        F = [{1, 2}, {2, 3}, {3, 4}]
        union = set().union(*F)
        print(f"\n  F = {{{', '.join(str(s) for s in F)}}}")
        print(f"  ∪F = {union}")

        # 후계자 함수에서의 사용
        print(f"\n  후계자 함수에서의 사용 (Phase 2 미리보기):")
        print(f"  S(n) = n ∪ {{n}}")
        print(f"  예: n = {{0, 1}} (= 2)")
        print(f"      S(n) = {{0, 1}} ∪ {{2}} = {{0, 1, 2}} (= 3)")
        print(f"  → 합집합 공리가 이 연산을 가능하게 합니다!")
        print()


# ============================================================================
#  공리 5: 멱집합 공리 (Axiom of Power Set)
# ============================================================================

class AxiomOfPowerSet:
    """
    멱집합 공리: 어떤 집합의 모든 부분집합을 모은 집합이 존재한다.

    형식적 진술:
        ∀A ∃P ∀B [ B ∈ P ⟺ B ⊆ A ]
    즉, P(A) = {B : B ⊆ A}

    왜 필요한가?
    -----------
    "부분집합 전체를 모은다"는 것은 매우 강력한 구성 능력입니다.
    유한 집합의 경우, |A| = n이면 |P(A)| = 2^n입니다.
    무한 집합의 경우, P(A)는 A보다 "더 큰" 무한이 됩니다.

    Phase 6에서 실수를 구성할 때 (데데킨트 절단),
    유리수의 부분집합으로 실수를 정의하므로 멱집합 공리가 핵심적입니다.

    이 공리가 없으면?
    ----------------
    실수를 구성할 수 없습니다.
    칸토어의 대각선 논증("무한의 크기가 다양하다")도 성립하지 않습니다.

    예시:
        1. P(∅) = {∅} — 부분집합은 ∅ 하나뿐
        2. P({a}) = {∅, {a}} — 크기 2
        3. P({a,b}) = {∅, {a}, {b}, {a,b}} — 크기 4
    """

    @staticmethod
    def demonstrate():
        """멱집합 공리를 시뮬레이션합니다."""
        print("=" * 60)
        print("공리 5: 멱집합 공리 (Axiom of Power Set)")
        print("  \"어떤 집합의 모든 부분집합을 모은 집합이 존재한다\"")
        print("=" * 60)

        def power_set(s):
            """유한 집합의 멱집합을 계산합니다."""
            s = list(s)
            result = []
            for i in range(2 ** len(s)):
                subset = frozenset(s[j] for j in range(len(s)) if i & (1 << j))
                result.append(subset)
            return result

        for name, A in [("∅", set()), ("{a}", {'a'}), ("{a,b}", {'a', 'b'}),
                        ("{a,b,c}", {'a', 'b', 'c'})]:
            ps = power_set(A)
            print(f"\n  P({name}) = {{{', '.join(str(set(x)) if x else '∅' for x in sorted(ps, key=len))}}}")
            print(f"  |{name}| = {len(A)},  |P({name})| = {len(ps)} = 2^{len(A)}")

        print(f"\n  💡 핵심 통찰:")
        print(f"  |A| = n이면 |P(A)| = 2^n")
        print(f"  칸토어가 증명한 것: |A| < |P(A)| (무한 집합에서도!)")
        print(f"  → 무한에도 '크기'가 다른 단계가 있다 (Phase 6에서 다시 만납니다)")
        print()


# ============================================================================
#  공리 6: 분류 공리꼴 (Axiom Schema of Separation / Specification)
# ============================================================================

class AxiomSchemaOfSeparation:
    """
    분류 공리꼴: 이미 있는 집합에서 조건을 만족하는 원소만 골라낼 수 있다.

    형식적 진술:
        임의의 성질 φ에 대해:
        ∀A ∃B ∀x [ x ∈ B ⟺ (x ∈ A ∧ φ(x)) ]
    즉, B = {x ∈ A : φ(x)}

    "공리꼴"(schema)이란?
    --------------------
    하나의 공리가 아니라, 각 성질 φ에 대해 하나씩의 공리가 있는 것입니다.
    무한히 많은 공리의 "틀"(template)이므로 "공리꼴"이라 합니다.

    왜 필요한가?
    -----------
    주어진 집합에서 원하는 원소를 걸러내는 능력을 보장합니다.
    동치류를 구성하는 데 핵심적으로 사용됩니다 (Phase 4, 5, 6).

    핵심: 러셀의 역설을 어떻게 막는가?
    -----------------------------------
    소박한 집합론: {x : φ(x)} — 아무 조건이나 집합을 만든다
    ZFC (분류 공리꼴): {x ∈ A : φ(x)} — 기존 집합에서 걸러낸다

    러셀의 역설: R = {x : x ∉ x}
    → 분류 공리꼴에서는 R = {x ∈ A : x ∉ x}만 가능
    → R ∈ R인지? R은 A의 부분집합이므로 "모든 집합의 모임"이 아님
    → 역설이 발생하지 않음!

    이 공리가 없으면?
    ----------------
    집합에서 조건부로 원소를 선택할 수 없습니다.
    "짝수의 집합", "소수의 집합" 같은 것을 만들 수 없습니다.

    예시:
        1. {x ∈ ℕ : x는 짝수} = {0, 2, 4, 6, ...}
        2. {x ∈ ℤ : x² < 10} = {-3, -2, -1, 0, 1, 2, 3}
        3. {x ∈ ℚ : x² < 2} (이것이 √2의 데데킨트 절단의 재료!)
    """

    @staticmethod
    def demonstrate():
        """분류 공리꼴과 러셀의 역설 차단을 시뮬레이션합니다."""
        print("=" * 60)
        print("공리 6: 분류 공리꼴 (Axiom Schema of Separation)")
        print("  \"이미 있는 집합에서 조건을 만족하는 원소만 골라낸다\"")
        print("=" * 60)

        # 예시: 조건부 추출
        A = set(range(20))
        evens = {x for x in A if x % 2 == 0}
        primes = {x for x in A if x > 1 and all(x % d != 0 for d in range(2, x))}
        print(f"\n  A = {{0, 1, ..., 19}}")
        print(f"  {{x ∈ A : x는 짝수}} = {sorted(evens)}")
        print(f"  {{x ∈ A : x는 소수}} = {sorted(primes)}")

        # 러셀의 역설이 어떻게 차단되는가
        print(f"\n  ⚠ 러셀의 역설과 분류 공리꼴:")
        print(f"  소박한 집합론: R = {{x : x ∉ x}}  → 모순!")
        print(f"  ZFC:          R = {{x ∈ A : x ∉ x}}  → A의 부분집합일 뿐")
        print(f"  R ∈ R인가? R ∉ R인가?")
        print(f"  → R ∈ A일 수도, 아닐 수도 있지만, 모순은 발생하지 않음")
        print(f"  → 핵심: '모든 집합의 모임'은 집합이 아니다! (고유 클래스)")
        print()


